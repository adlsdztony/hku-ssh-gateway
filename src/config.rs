use anyhow::{bail, ensure, Context, Result};
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct Config {
    pub vpn_user: String,
    pub vpn_server: String,
    pub vpn_useragent: String,
    pub allowed_targets: Vec<String>,
    pub project: String,
    pub keepalive: Keepalive,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct Keepalive {
    pub enabled: bool,
    pub host: String,
    pub port: u16,
    pub interval: u32,
    pub timeout: u32,
}

impl Default for Config {
    fn default() -> Self {
        Self {
            vpn_user: String::new(),
            vpn_server: "vpn2fa.hku.hk".into(),
            vpn_useragent: "AnyConnect".into(),
            allowed_targets: vec!["any".into()],
            project: "hku-ssh-gateway".into(),
            keepalive: Keepalive::default(),
        }
    }
}

impl Default for Keepalive {
    fn default() -> Self {
        Self {
            enabled: true,
            host: "gpu3gate1.cs.hku.hk".into(),
            port: 22,
            interval: 300,
            timeout: 5,
        }
    }
}

pub fn host(value: &str) -> bool {
    !value.is_empty()
        && value.as_bytes()[0].is_ascii_alphanumeric()
        && value
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || b"._-".contains(&c))
}

pub fn user(value: &str) -> bool {
    !value.is_empty()
        && value
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || b"._+-@".contains(&c))
}

pub fn ssh_user(value: &str) -> bool {
    !value.is_empty()
        && value
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || b"._-".contains(&c))
}

fn port(value: &str) -> bool {
    value.parse::<u16>().is_ok_and(|p| p > 0)
}

impl Config {
    pub fn validate(&self) -> Result<()> {
        ensure!(
            user(&self.vpn_user),
            "Set vpn_user to your HKU email address"
        );
        let valid_server = match self.vpn_server.split_once(':') {
            Some((name, p)) => host(name) && port(p),
            None => host(&self.vpn_server),
        };
        ensure!(
            valid_server,
            "vpn_server must be a hostname or IPv4 address, optionally :port"
        );
        ensure!(
            !self.vpn_useragent.is_empty()
                && self
                    .vpn_useragent
                    .bytes()
                    .all(|c| c.is_ascii_alphanumeric() || b"._/-".contains(&c)),
            "Invalid vpn_useragent"
        );
        ensure!(
            !self.project.is_empty()
                && self.project.as_bytes()[0].is_ascii_alphanumeric()
                && self
                    .project
                    .bytes()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || b"_-".contains(&c)),
            "project must contain lowercase letters, digits, underscores or hyphens"
        );
        ensure!(
            !self.allowed_targets.is_empty(),
            "allowed_targets cannot be empty"
        );
        if self.allowed_targets != ["any"] {
            for target in &self.allowed_targets {
                let (name, p) = target
                    .split_once(':')
                    .context("Each allowed target must be HOST:PORT, or use ['any']")?;
                ensure!(host(name) && port(p), "Invalid allowed target: {target}");
            }
        }
        ensure!(host(&self.keepalive.host), "Invalid keepalive.host");
        ensure!(self.keepalive.port > 0, "keepalive.port must be nonzero");
        ensure!(
            (1..=999999).contains(&self.keepalive.interval),
            "keepalive.interval must be 1..999999 seconds"
        );
        ensure!(
            (1..=999999).contains(&self.keepalive.timeout),
            "keepalive.timeout must be 1..999999 seconds"
        );
        Ok(())
    }

    pub fn dotenv(&self) -> Result<String> {
        self.validate()?;
        Ok(format!(
            "# Generated by hku. Edit config.toml instead.\nVPN_USER={}\nVPN_SERVER={}\nVPN_USERAGENT={}\nSSH_ALLOWED_TARGETS={}\nCOMPOSE_PROJECT_NAME={}\nKEEPALIVE_ENABLED={}\nKEEPALIVE_HOST={}\nKEEPALIVE_PORT={}\nKEEPALIVE_INTERVAL={}\nKEEPALIVE_TIMEOUT={}\n",
            self.vpn_user, self.vpn_server, self.vpn_useragent,
            self.allowed_targets.join(" "), self.project, self.keepalive.enabled,
            self.keepalive.host, self.keepalive.port, self.keepalive.interval, self.keepalive.timeout
        ))
    }
}

pub fn client_identity(value: &str) -> Result<()> {
    if value.contains(['\n', '\r', '"', '\0']) {
        bail!("Invalid client identity path");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    fn example() -> Config {
        Config {
            vpn_user: "example@connect.hku.hk".into(),
            ..Config::default()
        }
    }
    #[test]
    fn config_is_portable_and_roundtrips() {
        let config = example();
        let encoded = toml::to_string_pretty(&config).unwrap();
        let decoded: Config = toml::from_str(&encoded).unwrap();
        assert_eq!(decoded.dotenv().unwrap(), config.dotenv().unwrap());
        assert_eq!(decoded.allowed_targets, ["any"]);
        assert!(!encoded.to_lowercase().contains("tailscale"));
    }
    #[test]
    fn rejects_config_and_shell_injection() {
        let mut config = example();
        config.allowed_targets = vec!["host:22\nPermitRootLogin yes".into()];
        assert!(config.validate().is_err());
        config = example();
        config.vpn_user = "$(command)@hku.hk".into();
        assert!(config.dotenv().is_err());
        config = example();
        config.keepalive.interval = 0;
        assert!(config.validate().is_err());
        assert!(client_identity("key\nProxyCommand command").is_err());
    }
    #[test]
    fn explicit_targets_are_separate_from_keepalive() {
        let mut config = example();
        config.allowed_targets = vec!["other.hku.hk:2222".into(), "10.0.0.1:443".into()];
        assert!(config.validate().is_ok());
        config.vpn_server = "vpn2fa.hku.hk:4443".into();
        assert!(config.validate().is_ok());
        config.vpn_server = "vpn2fa.hku.hk:0".into();
        assert!(config.validate().is_err());
    }
}
